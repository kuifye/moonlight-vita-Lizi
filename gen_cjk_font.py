#!/usr/bin/env python3
"""
gen_cjk_font.py -- regenerate assets/cjk.ttf AND the font-routing table.

Run AFTER translate.py and BEFORE cmake (build_final.sh does this).

Why this exists
---------------
The Chinese UI needs glyphs that nerdfont.ttf does not have, so the build ships
a second font (a SimHei subset) and guilib.c routes code points to one font or
the other.  Two things must agree or the UI shows tofu boxes:

  1. the subset must contain every character the translated strings actually use
  2. the router must send exactly those characters to the subset, and nothing
     else -- in particular NOT the Nerd Font icons (U+F54C/F553 in the BMP
     Private Use Area), which live above 0x2500 and would otherwise be routed
     to a font that has no such glyph.

Earlier builds hard-coded a `cp >= 0x2500` threshold in guilib.c and the subset
was produced by an ad-hoc one-off.  This script makes both come from the same
scan of the same source, so they cannot drift.

What it writes
--------------
  assets/cjk.ttf          subset of the source font (only the needed characters)
  src/gui/cjk_ranges.h    the interval table guilib.c's use_cjk_font() consults

Usage:
  python3 gen_cjk_font.py <source-tree> --source-font /path/to/simhei.ttf
"""
import argparse
import glob
import io
import os
import re
import sys

from fontTools.ttLib import TTFont
from fontTools.subset import Subsetter, Options

STR = re.compile(r'"((?:[^"\\\n]|\\.)*)"')

# Nerd Font icon blocks: these must stay on nerdfont.ttf.
ICON_RANGES = [(0xE000, 0xF8FF), (0xF0000, 0xFFFFF)]

# Below this, glyphs come from nerdfont.ttf (ASCII, Latin-1, …, bullets).
CJK_FLOOR = 0x2500


def is_icon(cp):
    return any(a <= cp <= b for a, b in ICON_RANGES)


def scan_chars(root):
    """Every non-ASCII code point that appears in a C string literal."""
    files = sorted(set(glob.glob(root + "/src/**/*.c", recursive=True)
                       + glob.glob(root + "/src/*.c")
                       + glob.glob(root + "/src/**/*.h", recursive=True)
                       + glob.glob(root + "/src/*.h")))
    found = {}
    for fp in files:
        try:
            text = io.open(fp, encoding="utf-8").read()
        except (UnicodeDecodeError, OSError):
            continue
        for m in STR.finditer(text):
            for ch in m.group(1):
                cp = ord(ch)
                if cp >= CJK_FLOOR and not is_icon(cp):
                    found.setdefault(cp, os.path.relpath(fp, root))
    return found


def merge_intervals(cps):
    out = []
    for cp in sorted(cps):
        if out and cp == out[-1][1] + 1:
            out[-1][1] = cp
        else:
            out.append([cp, cp])
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("root", help="source tree (the vita-moonlight checkout)")
    ap.add_argument("--source-font", required=True,
                    help="full CJK font to subset (e.g. simhei.ttf)")
    ap.add_argument("--dry-run", action="store_true",
                    help="report only; write nothing")
    args = ap.parse_args()

    root = os.path.abspath(args.root)
    needed = scan_chars(root)
    if not needed:
        print("no CJK-range characters found in string literals -- nothing to do")
        return 0

    src = TTFont(args.source_font)
    src_cmap = src.getBestCmap()

    missing = [cp for cp in needed if cp not in src_cmap]
    if missing:
        print("ERROR: the source font lacks %d character(s) the UI uses:" % len(missing))
        for cp in missing:
            print("  U+%04X %s  (in %s)" % (cp, chr(cp), needed[cp]))
        return 1

    # ---- subset -------------------------------------------------------------
    opts = Options()
    opts.name_IDs = ["*"]
    opts.name_legacy = True
    opts.notdef_outline = True
    opts.recalc_bounds = True
    opts.hinting = True
    opts.layout_features = []
    opts.drop_tables += ["DSIG", "GPOS", "GSUB", "vhea", "vmtx", "kern",
                         "FFTM", "PfEd", "GDEF"]

    sub = Subsetter(options=opts)
    sub.populate(unicodes=sorted(needed))
    sub.subset(src)

    out_font = os.path.join(root, "assets", "cjk.ttf")
    out_hdr = os.path.join(root, "src", "gui", "cjk_ranges.h")

    if args.dry_run:
        print("would write %d characters into %s" % (len(needed), out_font))
        return 0

    src.save(out_font)

    # ---- routing table ------------------------------------------------------
    # Read the subset back: the router must describe the font that actually got
    # written, not the request that produced it.
    written = TTFont(out_font).getBestCmap()
    cps = sorted(written)
    intervals = merge_intervals(cps)

    hdr = io.open(out_hdr, "w", encoding="utf-8", newline="")
    hdr.write(
        "/* Generated by gen_cjk_font.py -- do not edit by hand.\n"
        " *\n"
        " * The code points assets/cjk.ttf actually contains, as merged\n"
        " * intervals.  guilib.c's use_cjk_font() binary-searches this table,\n"
        " * so the router and the font can never disagree.\n"
        " */\n"
        "#ifndef CJK_RANGES_H\n"
        "#define CJK_RANGES_H\n\n"
        "#define CJK_RANGE_COUNT %d\n\n"
        "static const unsigned int cjk_ranges[2 * CJK_RANGE_COUNT] = {\n" % len(intervals))
    for i in range(0, len(intervals), 8):
        chunk = intervals[i:i + 8]
        hdr.write("  " + ", ".join("0x%04X, 0x%04X" % (a, b) for a, b in chunk) + ",\n")
    hdr.write(
        "};\n\n"
        "static int cjk_range_contains(unsigned int cp) {\n"
        "  int lo = 0, hi = CJK_RANGE_COUNT - 1;\n"
        "  while (lo <= hi) {\n"
        "    int mid = (lo + hi) / 2;\n"
        "    unsigned int a = cjk_ranges[2 * mid];\n"
        "    unsigned int b = cjk_ranges[2 * mid + 1];\n"
        "    if (cp < a) hi = mid - 1;\n"
        "    else if (cp > b) lo = mid + 1;\n"
        "    else return 1;\n"
        "  }\n"
        "  return 0;\n"
        "}\n\n"
        "#endif /* CJK_RANGES_H */\n")
    hdr.close()

    print("characters needed : %d" % len(needed))
    print("characters written: %d" % len(cps))
    print("intervals         : %d" % len(intervals))
    print("font              : %s (%d bytes)" % (out_font, os.path.getsize(out_font)))
    print("header            : %s" % out_hdr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
